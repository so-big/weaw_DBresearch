def test_current_version_fk_is_checked_at_commit(engine: Engine) -> None:
    """Document and its first version can be inserted in either order within a transaction."""
    with engine.connect() as connection:
        with connection.begin():
            user = _user(connection)
            version_id = uuid.uuid4()
            doc = connection.execute(
                text(
                    "INSERT INTO documents (kind, funding_type, title, uploaded_by, "
                    "current_version_id) VALUES ('grant', 'external', 't', :u, :v) RETURNING id"
                ),
                {"u": user, "v": version_id},
            ).scalar_one()
            connection.execute(
                text(
                    "INSERT INTO document_versions (id, document_id, version_no, storage_key, "
                    "original_filename, mime_type, size_bytes, sha256_plain, wrapped_dek, kek_id, "
                    "uploaded_by) VALUES (:v, :d, 1, :key, 'a.pdf', 'application/pdf', 1, "
                    "'\\x00', '\\x00', 'k1', :u)"
                ),
                {"v": version_id, "d": doc, "key": uuid.uuid4().hex, "u": user},
            )
        # A dangling pointer is only rejected at COMMIT, because the FK is deferred.
        transaction = connection.begin()
        connection.execute(
            text("UPDATE documents SET current_version_id = :v WHERE id = :d"),
            {"v": uuid.uuid4(), "d": doc},
        )
        with pytest.raises(IntegrityError, match="fk_documents_current_version_id"):
            transaction.commit()
        transaction.rollback()
        with connection.begin():  # clean up the committed rows
            connection.execute(text("DELETE FROM documents WHERE id = :d"), {"d": doc})
            connection.execute(text("DELETE FROM users WHERE id = :u"), {"u": user})


def test_password_share_link_needs_password_hash(conn) -> None:
    user = _user(conn)
    doc = _document(conn, user)
    insert = text(
        "INSERT INTO share_links (document_id, token_hash, access, password_hash, expires_at, "
        "created_by) VALUES (:d, :t, :access, :pw, now() + interval '1 day', :u)"
    )
    conn.execute(insert, {"d": doc, "t": b"a", "access": "public", "pw": None, "u": user})
    with pytest.raises(IntegrityError, match="password_matches_access"), conn.begin_nested():
        conn.execute(insert, {"d": doc, "t": b"b", "access": "password", "pw": None, "u": user})


def test_space_insensitive_thai_search_uses_trigram_index(conn) -> None:
    user = _user(conn)
    doc = _document(conn, user)
    conn.execute(
        text("UPDATE documents SET search_text = :t WHERE id = :d"),
        {"t": "การพัฒนาประสิทธิภาพการจัดการข้อมูลนิสิต", "d": doc},
    )
    query = "ประสิทธิภาพ การจัดการ".replace(" ", "")
    found = (
        conn.execute(
            text("SELECT id FROM documents WHERE search_text ILIKE :q"), {"q": f"%{query}%"}
        )
        .scalars()
        .all()
    )
    assert found == [doc]
    conn.execute(text("SET LOCAL enable_seqscan = off"))
    plan = (
        conn.execute(
            text("EXPLAIN SELECT id FROM documents WHERE search_text ILIKE :q"), {"q": f"%{query}%"}
        )
        .scalars()
        .all()
    )
    assert any("documents_text_trgm" in line for line in plan)


