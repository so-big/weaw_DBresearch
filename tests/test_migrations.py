def test_database_uses_icu_thai_locale(engine: Engine) -> None:
    with engine.connect() as conn:
        provider, locale = conn.execute(
            text(
                "SELECT datlocprovider, datlocale FROM pg_database "
                "WHERE datname = current_database()"
            )
        ).one()
    assert (provider, locale) == ("i", "th-TH")


def test_seed_data(engine: Engine) -> None:
    with engine.connect() as conn:
        groups = dict(
            conn.execute(
                text(
                    "SELECT g.key, count(c.id) FROM category_groups g "
                    "LEFT JOIN categories c ON c.group_id = g.id GROUP BY g.key"
                )
            ).all()
        )
        aliases = conn.execute(
            text("SELECT aliases FROM category_groups WHERE key = 'research_type'")
        ).scalar_one()
        ttl = conn.execute(
            text("SELECT value FROM settings WHERE key = 'share.max_ttl_user_hours'")
        ).scalar_one()
    assert groups == {
        "agency": 2,
        "grant_programme": 1,
        "research_type": 6,  # + ประยุกต์ (round-1 form)
        "research_group": 8,  # + มนุษยศาสตร์และสังคมศาสตร์
        "grant_type": 2,
        "discipline": 12,  # the 12 NRCT disciplines printed on the form
    }
    assert aliases == ["ประเภทวิจัย"]
    assert ttl == 168


