def _user(conn) -> uuid.UUID:
    return conn.execute(
        text("INSERT INTO users (email, display_name) VALUES (:email, 'Test') RETURNING id"),
        {"email": f"{uuid.uuid4().hex}@example.test"},
    ).scalar_one()


def _document(conn, user_id, reference_no=None, deleted=False) -> uuid.UUID:
    return conn.execute(
        text(
            "INSERT INTO documents "
            "(kind, funding_type, title, reference_no, uploaded_by, deleted_at) "
            "VALUES ('contract', 'internal', 'ทดสอบ', :ref, :user, "
            "CASE WHEN :deleted THEN now() END) RETURNING id"
        ),
        {"ref": reference_no, "user": user_id, "deleted": deleted},
    ).scalar_one()


def test_contract_number_parts_are_generated(conn) -> None:
    user = _user(conn)
    doc = _document(conn, user, "R2568A034")
    odd = _document(conn, user, "OLD-123")
    rows = dict(
        (row[0], row[1:])
        for row in conn.execute(
            text("SELECT id, ref_year_be, ref_series, ref_seq FROM documents WHERE id IN (:a, :b)"),
            {"a": doc, "b": odd},
        )
    )
    assert rows[doc] == (2568, "A", 34)
    assert rows[odd] == (None, None, None)


